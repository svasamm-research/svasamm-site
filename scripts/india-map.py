#!/usr/bin/env python3
"""Shrink the India state map into lib/india-map.ts for the home page's "Where we work".

Source: @svg-maps/india 2.0.0 (npm), from mapsvg.com — CC BY 4.0, so the page credits it.
Its paths are ~176 KB; simplified (Douglas-Peucker, 1 unit on a 612x696 box) they are
small enough to inline. Re-run only to change the tolerance or the source:

    npm pack @svg-maps/india && tar xzf svg-maps-india-*.tgz
    python3 scripts/india-map.py package/index.js
"""
import json, re, sys

src = open(sys.argv[1]).read()
data = json.loads(src[src.index("{"):src.rindex("}") + 1])


def rings(d):
    """Absolute point rings from the source's m/l/L/z paths (implicit pairs are lines)."""
    out, ring, cx, cy, sx, sy, cmd = [], [], 0.0, 0.0, 0.0, 0.0, None
    nums = []
    for tok in re.findall(r"[mlLzZ]|-?\d*\.?\d+(?:e-?\d+)?", d):
        if tok in "mlLzZ":
            if tok in "zZ":
                if ring:
                    out.append(ring)
                ring, cx, cy = [], sx, sy
            cmd, nums = tok, []
            continue
        nums.append(float(tok))
        if len(nums) < 2:
            continue
        x, y = nums
        nums = []
        if cmd == "m":
            if ring:
                out.append(ring)
            cx, cy = cx + x, cy + y
            sx, sy, ring, cmd = cx, cy, [(cx, cy)], "l"
        elif cmd == "l":
            cx, cy = cx + x, cy + y
            ring.append((cx, cy))
        elif cmd == "L":
            cx, cy = x, y
            ring.append((cx, cy))
    if ring:
        out.append(ring)
    return out


def simplify(pts, eps):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    n = (dx * dx + dy * dy) ** 0.5 or 1e-9
    i, dmax = 0, 0.0
    for k in range(1, len(pts) - 1):
        d = abs(dy * pts[k][0] - dx * pts[k][1] + x2 * y1 - y2 * x1) / n
        if d > dmax:
            i, dmax = k, d
    if dmax <= eps:
        return [pts[0], pts[-1]]
    return simplify(pts[: i + 1], eps)[:-1] + simplify(pts[i:], eps)


f = lambda v: str(round(v))
states = []
for loc in data["locations"]:
    parts = []
    for r in rings(loc["path"]):
        s = simplify(r, 1.0)
        if len(s) >= 3:
            parts.append("M" + "L".join(f"{f(x)} {f(y)}" for x, y in s) + "Z")
    states.append({"id": loc["id"], "name": loc["name"], "d": "".join(parts)})

with open("lib/india-map.ts", "w") as o:
    o.write("// GENERATED by scripts/india-map.py from @svg-maps/india (mapsvg.com, CC BY 4.0) — do not hand-edit.\n")
    o.write(f'export const INDIA_VIEWBOX = "{data["viewBox"]}";\n')
    o.write("export const INDIA_STATES: { id: string; name: string; d: string }[] = " + json.dumps(states) + ";\n")
print(sum(len(s["d"]) for s in states), "bytes of path data")
