#!/usr/bin/env python3
"""Outline the product wordmarks into SVG paths, so the site draws each product's
real lockup without loading its font (Inter Tight for Millingo, Manrope for T4Suite
and Lucoze). Writes lib/wordmarks.ts. Re-run only if a wordmark changes.

Sources (the designs these copy, never redraw):
- Millingo: the Millingo canvas (https://claude.ai/artifact/1seLhA8GQtNnUga7t7FfTz,
  Main.dc.html BRAND, 8 Oct 2026 poster) — Inter Tight 800, -0.03em, navy "Millin" + yellow "go".
- T4Suite: packages/t4suite/src/components/Brand.tsx and t4suite-site BrandMark.astro —
  Manrope 700, "T4" #2563EB + "Suite" ink, letter-spacing -1 at 38px.
- Lucoze: lucoze-website Logo.astro — Manrope 700, -0.03em, ink #1f1d1a.

Usage: python3 scripts/outline-wordmarks.py <inter-tight.woff2> <manrope-wght.woff2>
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen


def kern_table(font):
    """Pair adjustments (first glyph, second glyph) -> x advance delta, from GPOS."""
    pairs, gpos = {}, font["GPOS"].table if "GPOS" in font else None
    if not gpos:
        return pairs
    for lookup in gpos.LookupList.Lookup:
        subs = lookup.SubTable
        if lookup.LookupType == 9:
            subs = [s.ExtSubTable for s in subs]
        for st in subs:
            if getattr(st, "LookupType", 2) != 2:
                continue
            firsts = st.Coverage.glyphs
            if st.Format == 1:
                for g1, ps in zip(firsts, st.PairSet):
                    for pv in ps.PairValueRecord:
                        v = pv.Value1.XAdvance if pv.Value1 and hasattr(pv.Value1, "XAdvance") else 0
                        pairs.setdefault((g1, pv.SecondGlyph), v)
            elif st.Format == 2:
                c1, c2 = st.ClassDef1.classDefs, st.ClassDef2.classDefs
                for g1 in firsts:
                    r1 = st.Class1Record[c1.get(g1, 0)]
                    for g2 in font.getGlyphOrder():
                        rec = r1.Class2Record[c2.get(g2, 0)]
                        v = rec.Value1.XAdvance if rec.Value1 and hasattr(rec.Value1, "XAdvance") else 0
                        if v:
                            pairs.setdefault((g1, g2), v)
    return pairs


def outline(path, weight, runs, size, tracking_em):
    """runs: [(text, colour)]. Returns (width, height, [(d, colour)]) at `size` px."""
    font = instantiateVariableFont(TTFont(path), {"wght": weight})
    upm, cmap, gs = font["head"].unitsPerEm, font.getBestCmap(), font.getGlyphSet()
    hmtx, kern = font["hmtx"], kern_table(font)
    asc = font["hhea"].ascent
    scale = size / upm
    x, prev, out = 0.0, None, []
    for text, colour in runs:
        pen = SVGPathPen(gs)
        for ch in text:
            g = cmap[ord(ch)]
            if prev:
                x += kern.get((prev, g), 0)
            gs[g].draw(TransformPen(pen, (scale, 0, 0, -scale, x * scale, asc * scale)))
            x += hmtx[g][0] + tracking_em * upm
            prev = g
        out.append((pen.getCommands(), colour))
    x -= tracking_em * upm
    return round(x * scale, 2), round((asc - font["hhea"].descent) * scale, 2), out


inter, manrope = sys.argv[1], sys.argv[2]
marks = {
    "millingo": outline(inter, 800, [("Millin", "#0E1E5B"), ("go", "#F2A900")], 100, -0.03),
    "t4suite": outline(manrope, 700, [("T4", "#2563EB"), ("Suite", "INK")], 100, -1 / 38),
    "lucoze": outline(manrope, 700, [("Lucoze", "INK")], 100, -0.03),
}
lines = ["// GENERATED by scripts/outline-wordmarks.py — do not hand-edit. Each product's",
         "// wordmark as outlined paths at a 100px font size; \"INK\" is the text colour of the",
         "// ground it sits on. Sources are named in the script.",
         "export const WORDMARKS: Record<string, { w: number; h: number; runs: { d: string; fill: string }[] }> = {"]
for k, (w, h, runs) in marks.items():
    rs = ", ".join('{ d: "%s", fill: "%s" }' % (d, c) for d, c in runs)
    lines.append(f"  {k}: {{ w: {w}, h: {h}, runs: [{rs}] }},")
lines.append("};\n")
open("lib/wordmarks.ts", "w").write("\n".join(lines))
for k, (w, h, _) in marks.items():
    print(k, w, h)
